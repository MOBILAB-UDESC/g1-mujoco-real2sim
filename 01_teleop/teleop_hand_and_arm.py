#  -------        ---------                -----------                -----------            ---------
#   state          [Ready]      ==>        [Recording]     ==>         [AutoSave]     -->     [Ready]
#  -------        ---------      |         -----------      |         -----------      |     ---------
#   START           True         |manual      True          |manual      True          |        True
#   READY           True         |set         False         |set         False         |auto    True
#   RECORD_RUNNING  False        |to          True          |to          False         |        False
#                                ∨                          ∨                          ∨
#   RECORD_TOGGLE   False       True          False        True          False                  False
#  -------        ---------                -----------                 -----------            ---------
#  ==> manual: when READY is True, set RECORD_TOGGLE=True to transition.
#  --> auto  : Auto-transition after saving data.

def on_press(key):
    global STOP, START, RECORD_TOGGLE
    if key == 'r':
        START = True
    elif key == 'q':
        START = False
        STOP = True
    elif key == 's' and START == True:
        RECORD_TOGGLE = True
    elif key == 'a':
        START = False
    else:
        logger_mp.warning(f"[on_press] {key} was pressed, but no action is defined for this key.")

WAIST_YAW_INDEX = 12  # G1 motor index of the waist yaw joint (G1_29_JointIndex.kWaistYaw)


class WaistStick:
    """Right stick -> waist yaw target and body turn rate, like the simulator's own walking controller.

    The stick twists the waist. While walking, the body turns toward where the torso looks (so the twist
    unwinds), and a twist past the limit turns the body instead. step() returns (waist target [rad], body
    turn rate [rad/s] for LocoClient.Move).
    """

    def __init__(self, q0=0.0, limit=1.0, follow_rate=1.5, max_turn=0.6):
        self.q, self.limit, self.follow_rate, self.max_turn = float(q0), float(limit), follow_rate, max_turn

    def step(self, rate, walking, dt):
        waist = self.q + rate * dt
        turn = 0.0
        if walking:
            turn = float(np.clip(waist * self.follow_rate, -self.max_turn, self.max_turn))
            waist -= turn * dt
        over = waist - float(np.clip(waist, -self.limit, self.limit))
        if over:
            turn = float(np.clip(turn + over / dt, -self.max_turn, self.max_turn))
            waist -= over
        self.q = waist
        return waist, turn


def get_state() -> dict:
    """Return current heartbeat state"""
    global START, STOP, RECORD_RUNNING, READY
    return {
        "START": START,
        "STOP": STOP,
        "READY": READY,
        "RECORD_RUNNING": RECORD_RUNNING,
    }
def handle_controller_buttons(tele_data, prev, record_enabled):
    """Rising-edge detection for Quest buttons. Mutates the globals the keyboard handler uses."""
    global START, STOP, RECORD_TOGGLE
    a = bool(tele_data.right_ctrl_aButton)   # A: quit
    b = bool(tele_data.right_ctrl_bButton)   # B: stop teleop
    x = bool(tele_data.left_ctrl_aButton)    # X: start teleop
    y = bool(tele_data.left_ctrl_bButton)    # Y: record toggle

    if a and not prev["A"]:
        START = False
        STOP = True
    if b and not prev["B"]:
        START = False
    if x and not prev["X"]:
        START = True
    if y and not prev["Y"] and START and record_enabled:
        RECORD_TOGGLE = True

    prev.update(A=a, B=b, X=x, Y=y)

